// Writes plugin/Source/dsp/Params.gen.h from src/dsp/params.ts: the flat
// parameter list, the module library (each module's knobs) and the factory
// rigs, so the C++ engine and the host see exactly what the web version
// sees. Run after changing params.ts:
//
//   node scripts/gen-plugin.ts

import { writeFileSync } from 'node:fs';
import {
  PARAMS, MODULES, RIGS, NSLOTS, MAX_KNOBS, NMODULES, SLOT_BASE, SLOT_STRIDE, P_INGAIN, P_HEAT, P_VOLUME, P_IFACE,
  rigValues, diffValues, type ParamDef,
} from '../src/dsp/params.ts';
import { VOICINGS } from '../src/dsp/amp.ts';

const out = 'plugin/Source/dsp/Params.gen.h';
const num = (x: number) => {
  const s = String(x);
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const str = (s: string | undefined) => (s === undefined ? 'nullptr' : JSON.stringify(s));
const SCALE = { lin: 'Lin', log: 'Log', int: 'Int', enum: 'Enum', bool: 'Bool' } as const;
const def = (p: ParamDef, labels: string) =>
  `{ ${str(p.id)}, ${str(p.name)}, ${str(p.group)}, ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, Scale::${SCALE[p.scale]}, ${str(p.unit)}, ${labels} }`;

const L: string[] = [];
L.push('// Generated by scripts/gen-plugin.ts from src/dsp/params.ts. Do not edit.');
L.push('#pragma once');
L.push('');
L.push('namespace pedalboard {');
L.push('');
L.push('enum class Scale { Lin, Log, Int, Enum, Bool };');
L.push('');
L.push('struct ParamDef {');
L.push('  const char* id; const char* name; const char* group;');
L.push('  double min, max, def; Scale scale; const char* unit;');
L.push('  const char* const* labels; int numLabels;');
L.push('};');
L.push('');
L.push('namespace P {');
L.push('enum : int {');
for (const p of PARAMS) L.push(`  ${p.id},`);
L.push('  COUNT');
L.push('};');
L.push('}');
L.push('');
L.push('constexpr int NUM_PARAMS = P::COUNT;');
L.push(`constexpr int NSLOTS = ${NSLOTS}, MAX_KNOBS = ${MAX_KNOBS}, NMODULES = ${NMODULES};`);
L.push(`constexpr int SLOT_BASE = ${SLOT_BASE}, SLOT_STRIDE = ${SLOT_STRIDE};`);
L.push(`constexpr int P_INGAIN = ${P_INGAIN}, P_HEAT = ${P_HEAT}, P_VOLUME = ${P_VOLUME}, P_IFACE = ${P_IFACE};`);
L.push('/** Not part of a rig: kept when a rig loads. */');
L.push('constexpr bool notInRig(int i) { return i == P_VOLUME || i == P_IFACE; }');
L.push(`enum : int { ${MODULES.map((m, i) => `M_${m.id.toUpperCase()} = ${i}`).join(', ')} };`);
L.push('');
PARAMS.forEach((p) => {
  if (p.labels) L.push(`inline constexpr const char* LABELS_${p.id}[] = { ${p.labels.map((l) => JSON.stringify(l)).join(', ')} };`);
});
L.push('');
L.push('inline constexpr ParamDef PARAMS[NUM_PARAMS] = {');
for (const p of PARAMS) L.push(`  ${def(p, p.labels ? `LABELS_${p.id}, ${p.labels.length}` : 'nullptr, 0')},`);
L.push('};');
L.push('');
L.push('// ---- the module library: what each slot knob means for each module');
L.push('');
L.push('struct ModuleDef { const char* id; const char* name; bool stereo; const ParamDef* knobs; int numKnobs; };');
L.push('');
for (const m of MODULES) {
  m.knobs.forEach((k) => {
    if (k.labels) L.push(`inline constexpr const char* KLABELS_${m.id}_${k.id}[] = { ${k.labels.map((l) => JSON.stringify(l)).join(', ')} };`);
  });
  if (m.knobs.length) {
    L.push(`inline constexpr ParamDef KNOBS_${m.id}[] = {`);
    for (const k of m.knobs) L.push(`  ${def(k, k.labels ? `KLABELS_${m.id}_${k.id}, ${k.labels.length}` : 'nullptr, 0')},`);
    L.push('};');
  }
}
L.push('');
L.push('inline constexpr ModuleDef MODULES[NMODULES] = {');
for (const m of MODULES) L.push(`  { ${str(m.id)}, ${str(m.name)}, ${m.stereo}, ${m.knobs.length ? `KNOBS_${m.id}` : 'nullptr'}, ${m.knobs.length} },`);
L.push('};');
L.push('');
L.push('// ---- the factory rigs, as the parameters that differ from the defaults');
L.push('');
L.push('struct PresetValue { int id; double value; };');
L.push('struct Preset { const char* name; const char* tag; const PresetValue* values; int count; };');
L.push('');
const diffs = RIGS.map((r) => diffValues(rigValues(r)));
diffs.forEach((d, i) => {
  const vals = Object.entries(d).map(([id, v]) => `{ P::${id}, ${num(v!)} }`);
  L.push(`inline constexpr PresetValue RIG_${i}[] = { ${vals.join(', ')} };`);
});
L.push('');
L.push(`constexpr int NUM_PRESETS = ${RIGS.length};`);
L.push('inline constexpr Preset PRESETS[NUM_PRESETS] = {');
RIGS.forEach((r, i) => L.push(`  { ${str(r.name)}, ${str(r.tag)}, RIG_${i}, ${Object.keys(diffs[i]).length} },`));
L.push('};');
L.push('');
L.push('} // namespace pedalboard');
L.push('');

writeFileSync(out, L.join('\n'));

// the amps' voicing table (amp.ts VOICINGS), so the C++ amp is built from the same values
{
  const V: string[] = ['// Generated by scripts/gen-plugin.ts from src/dsp/amp.ts. Do not edit.', '#pragma once', '', 'inline const Voicing VOICINGS[NVOICINGS] = {'];
  const n = (x: number) => num(x);
  for (const v of VOICINGS) {
    const st = Array.from({ length: 4 }, (_, k) => {
      const s = v.stages[k] ?? v.stages[0];
      return `{ ${s.kind}, ${n(s.ck)}, ${n(s.cc)}, ${n(s.r1)}, ${n(s.c1)}, ${n(s.r2)}, ${s.pot}, ${n(s.cb)}, ${n(s.stop)}, ${n(s.cp)} }`;
    });
    const k = v.stack, p = v.power;
    V.push(`  { ${v.stages.length}, { ${st.join(', ')} }, ${n(v.potLo)}, ${v.stackAt}, ${v.cf}, { ${k.topo}, ${n(k.R1)}, ${n(k.R2)}, ${n(k.R3)}, ${n(k.R4)}, ${n(k.C1)}, ${n(k.C2)}, ${n(k.C3)} }, ${n(v.trim)}, ${n(v.follow)}, ${n(v.bias)}, ${n(v.gpi)}, ${v.mv}, ${v.pres}, { ${p.se}, ${n(p.cut)}, ${n(p.nfb)}, ${n(p.imb)}, ${n(p.pi)}, ${n(p.knee)}, ${n(p.zp)} } },`);
  }
  V.push('};', '');
  writeFileSync('plugin/Source/dsp/Voicings.gen.h', V.join('\n'));
}
console.log(`wrote ${out}: ${PARAMS.length} params, ${MODULES.length} modules, ${RIGS.length} rigs`);
